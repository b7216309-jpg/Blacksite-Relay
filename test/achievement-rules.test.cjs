function scanner(h, hz) {
  const inspect = h.run('() => ({level:bypassLevel,gauge:bypassGauge,target:bypassTarget,tolerance:bypassTolerance,speed:bypassSpeed,direction:bypassDirection,screen:currentPresentationScreen()})');
  let timestamp = 0;
  return {
    inspect,
    findVisibleHit() {
      let previous = inspect();
      let maxForwardStep = 0;
      for (let frame = 0; frame < hz * 8; frame++) {
        h.now(timestamp);
        h.frame(timestamp); // Run only the real queued requestAnimationFrame callbacks.
        timestamp += 1000 / hz;
        const current = inspect();
        maxForwardStep = Math.max(maxForwardStep,current.gauge-previous.gauge);
        assert.equal(current.screen, 'bypass');
        assert.ok(Number.isFinite(current.gauge) && current.gauge >= 0 && current.gauge <= 100);
        const rendered = Number.parseFloat(h.elements.get('bypass-cursor').style.left);
        assert.equal(rendered, current.gauge, 'stops use the scanner position actually painted for this frame');
        if (Math.abs(current.gauge - current.target) <= current.tolerance) {
          assert.equal(h.elements.get('bypass-cursor').dataset.proximity, 'inside');
          return { ...current, previousGauge:previous.gauge, maxForwardStep, renderedFrames:frame + 1 };
        }
        previous = current;
      }
      const blocked = inspect();
      assert.fail(`No visible hit at ${hz}Hz: level=${blocked.level}, target=${blocked.target}, speed=${blocked.speed}, tolerance=${blocked.tolerance}, gauge=${blocked.gauge}`);
    },
    stop() {
      const hit = this.findVisibleHit();
      h.context.attemptBypass();
      return hit;
    }
  };
}

function mixedTargetRolls() {
  // Valid Math.random outputs, including both target-range boundaries and the
  // old level-28 blind spot at 22.5. Targets are generated by startBypassLevel.
  return Array.from({length:50},(_,level)=>level===27 ? 2.5/60 : [0,1-Number.EPSILON/2,.5,(level*37%101)/101][level%4]);
}

for (const hz of refreshRates) {
  test(`Legendary Cracker is reachable through 50 painted scanner stops at ${hz}Hz`, async () => {
    const rolls=mixedTargetRolls(), expectedTargets=rolls.map(roll=>20+roll*60);
    const h=harness(false,rolls), driver=scanner(h,hz), observed=[];
    h.run('risk=100;bypassCharge=15;bypass()');
    for (let stop=0;stop<50;stop++) {
      const before=driver.inspect();
      assert.equal(before.level,stop+1);
      assert.equal(before.target,expectedTargets[stop]);
      assert.ok(before.target>=20 && before.target<=80);
      assert.equal(h.run('achievements.legendaryCrack.unlocked'),false,'the milestone is not awarded before the 50th successful stop');
      observed.push(driver.stop());
      assert.equal(h.rafs.size,stop===49?0:1,'level transitions retain exactly one active scanner loop');
    }
    // Verify the curve after physical completion, so old code first fails on
    // an unreachable visible target rather than merely on a constant value.
    for(const hit of observed) {
      const expected=Math.min(8,.8*Math.pow(1.12,hit.level-1));
      assert.ok(Math.abs(hit.speed-expected)<1e-10,'original early acceleration followed by the 8-unit cap');
      assert.ok(hit.tolerance>=5 && hit.tolerance<=18);
    }
    const results=h.events.filter(event=>event.type==='risk:protocol'&&event.detail.game==='bypass'&&event.detail.phase==='result');
    assert.equal(results.length,1);
    assert.equal(results[0].detail.success,true);
    assert.equal(results[0].detail.stops,50);
    assert.equal(results[0].detail.rewardReduction,100);
    assert.equal(h.run('risk'),0);
    assert.equal(h.run('currentPresentationScreen()'),'game');
    assert.equal(h.run('bypassCharge'),0);
    assert.equal(h.calls(),50,'only the 50 generated targets consume gameplay randomness');
    await h.run('saveWritePromise');
    for(const key of ['lockpickApp','masterHacker','legendaryCrack']) {
      assert.equal(h.run(`achievements.${key}.unlocked`),true);
      assert.equal(h.saves.at(-1).achievements[key].unlocked,true,'earned milestone is saved');
    }
  });

  test(`minimum-width targets remain visible throughout 20..80 at maximum speed and ${hz}Hz`, () => {
    const rolls=Array(22).fill(.5), h=harness(false,rolls), driver=scanner(h,hz);
    h.run('bypassCharge=15;bypass()');
    // Earn the maximum-speed/minimum-width state; do not assign gauge, target,
    // speed or tolerance. The runtime's normal level transition establishes it.
    for(let stop=0;stop<21;stop++)driver.stop();
    assert.equal(driver.inspect().level,22);
    assert.equal(driver.inspect().speed,8);
    assert.equal(driver.inspect().tolerance,5);
    const candidates=[...Array.from({length:600},(_,i)=>i/600),1-Number.EPSILON/2];
    for(const roll of candidates) {
      rolls.push(roll);
      h.context.startBypassLevel();
      const target=driver.inspect();
      assert.equal(target.target,20+roll*60,'ordinary target RNG selects the tested center');
      assert.equal(h.elements.get('bypass-target').style.width,'10%');
      const hit=driver.findVisibleHit();
      assert.equal(hit.direction,1,'every target is visible during the first left-to-right pass');
      assert.ok(hit.maxForwardStep<=8+1e-10,'no simulated step can jump over a 10-unit target window');
    }
    assert.equal(h.calls(),22+candidates.length);
    h.run('exitBypassGame()');assert.equal(h.rafs.size,0);
  });
}

